"""PROTOTYPE - throwaway. Generates the same random expressions for four variants.

Statement i is `auto t_i = E_i(x, y, t_{i-1})` with x of shape (N, 1) and y of shape (1, M),
so every statement broadcasts. Every 4th statement and the last one are also stored in an
output tensor. Usage: python3 gen.py OUTDIR K [K ...]
"""
import random
import sys
from pathlib import Path

DEPTH = 4


def gen_expr(rng, depth, prev, used):
    if depth == 0:
        choices = ["x", "y"]
        if prev and not used[0]:
            choices += [prev] * 2
        leaf = rng.choice(choices)
        if leaf == prev:
            used[0] = True
        return leaf
    k = rng.randrange(10)
    sub = lambda: gen_expr(rng, depth - 1, prev, used)
    dup = lambda: gen_expr(rng, depth - 1, None, used)  # duplicated subtrees never contain prev
    if k == 0:
        return f"({sub()} + {sub()})"
    if k == 1:
        return f"({sub()} - {sub()})"
    if k == 2:
        return f"({sub()} * {sub()})"
    if k == 3:
        e = dup()
        return f"({sub()} / (1.0 + {e} * {e}))"
    if k == 4:
        return f"({rng.choice(['0.5', '1.5', '2.0', '3.0'])} * {sub()})"
    if k == 5:
        return f"NS::sin({sub()})"
    if k == 6:
        return f"NS::cos({sub()})"
    if k == 7:
        return f"NS::tanh({sub()})"
    if k == 8:
        e = dup()
        return f"NS::exp(-({e} * {e}))"
    e = dup()
    return f"NS::sqrt(1.0 + {e} * {e})"


def statements(k):
    rng = random.Random(11)
    out = []
    for i in range(k):
        prev = f"t{i - 1}" if i > 0 else None
        used = [False]
        e = gen_expr(rng, DEPTH, prev, used)
        if prev and not used[0]:  # keep the chain: every statement depends on the previous one
            e = f"({e} + 0.5 * {prev})"
        out.append(e)
    return out


def outputs(k):
    return [i for i in range(k) if (i + 1) % 4 == 0 or i == k - 1]


VARIANTS = {
    "xt_lazy": dict(
        head="#include <xtensor/containers/xtensor.hpp>\n#include <xtensor/core/xmath.hpp>\n",
        ns="xt", tensor="xt::xtensor<double, 2>", decl="auto", tail=""),
    "xt_eval": dict(
        head="#include <xtensor/containers/xtensor.hpp>\n#include <xtensor/core/xmath.hpp>\n",
        ns="xt", tensor="xt::xtensor<double, 2>", decl="xt::xtensor<double, 2>", tail=""),
    "et": dict(head='#include "et.hpp"\n', ns="et", tensor="et::tensor", decl="auto", tail=""),
    "tl": dict(head='#include "tl_front.hpp"\n', ns="tl", tensor="tl::tensor", decl="auto",
               tail="    tl::eval_all();\n"),
}


def render(variant, k):
    v = VARIANTS[variant]
    lines = [f"// GENERATED by gen.py - PROTOTYPE, {variant}, K={k}", v["head"]]
    lines.append(f"void compute_{variant}_{k}(const {v['tensor']}& x, const {v['tensor']}& y, {v['tensor']}* out)")
    lines.append("{")
    outs = outputs(k)
    for i, e in enumerate(statements(k)):
        lines.append(f"    {v['decl']} t{i} = {e.replace('NS', v['ns'])};")
        if i in outs:
            lines.append(f"    out[{outs.index(i)}] = t{i};")
    lines.append(v["tail"] + "}")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    outdir = Path(sys.argv[1])
    outdir.mkdir(parents=True, exist_ok=True)
    for k in map(int, sys.argv[2:]):
        for variant in VARIANTS:
            (outdir / f"{variant}_{k}.cpp").write_text(render(variant, k))
        print(f"K={k}: {len(outputs(k))} outputs")
